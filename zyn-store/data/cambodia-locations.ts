function splitBilingualLocation(location: string) {
  const match = /^(.*?)\s*\((.*)\)$/.exec(location);

  return {
    en: match?.[1] ?? location,
    km: match?.[2] ?? location,
  };
}

export function getProvinceLabel(province: string, language: LocationLanguage) {
  const labels = CAMBODIA_PROVINCE_LABELS[province];
  return labels ? labels[language] : province;
}

export function getLocationValue(location: string) {
  return splitBilingualLocation(location).en;
}

export function getLocationLabel(location: string, language: LocationLanguage) {
  return splitBilingualLocation(location)[language];
}
